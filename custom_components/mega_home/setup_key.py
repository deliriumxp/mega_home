"""Ключ настройки — одна строка вместо двух полей мастера.

Вид: `https://mm.example.ru#<токен объекта>` (адрес менеджера, `#`, токен). Менеджер выдаёт её
инсталлятору целиком, а мастеру остаётся вставить. Чистая функция без Home Assistant: её
проверяют тесты, а мастер только зовёт.

⚠ Ввод без `#` — голый токен (прежний способ «адрес + токен»): адрес тогда берётся из
отдельного поля. Адрес всегда перед ПЕРВЫМ `#` — в адресе фрагмента не бывает, а токен
менеджер выдаёт без `#`; всё, что после первого `#`, — токен как есть.
"""

from __future__ import annotations

SEPARATOR = "#"


def parse_key(raw: str, manager_url: str = "") -> tuple[str, str] | None:
    """Вернуть `(адрес, токен)` или `None`, если из ввода их не собрать.

    `manager_url` — запасной адрес для голого токена; при ключе целиком он не используется.
    Адрес приходит без пробелов и без слэшей на конце — как его хранит запись.
    """
    text = (raw or "").strip()
    if SEPARATOR in text:
        url, _, token = text.partition(SEPARATOR)
    else:
        url, token = manager_url, text
    url = (url or "").strip().rstrip("/")
    token = token.strip()
    if not url or not token:
        return None
    return url, token
