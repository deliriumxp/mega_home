# --- TRASSIR: видеонаблюдение объекта ---
#
# Адрес и порты приезжают блоком `trassir` в конфиге дома, а УЧЁТКА — отдельным
# маршрутом: тело конфига мы отдаём браузеру жильца как есть, и пароль
# администратора видеонаблюдения в нём означал бы доступ к камерам любому в
# Wi-Fi объекта. Перечитываем её, когда в конфиге сменился отпечаток
# `trassir.credentials` (на содержимое он не разбирается, только сравнивается).
API_TRASSIR = "/inbound/home-config/trassir"

# Сессия SDK живёт 15 минут — обновляем чуть раньше, чтобы не ловить отказ на
# ровном месте. Логин не чаще одного раза в 5 секунд: чаще — бан АДРЕСА.
TRASSIR_SESSION_TTL = 14 * 60
TRASSIR_LOGIN_GAP = 5
TRASSIR_TIMEOUT = 15

# Опрос событий. ⚠ `/events` — очередь СЕССИИ: отдаётся всё, что случилось с
# прошлого вызова, а новая сессия получает бэклог, обрезанный сотней событий.
# Значит потеря наступает не «через N секунд», а когда между опросами накопилось
# больше сотни: на стенде с 12 камерами это ~9 минут, и пять секунд оставляют
# запас на порядок.
TRASSIR_POLL_INTERVAL = 5
# Список камер на объекте меняется раз в жизни, а имя камеры нужно каждому событию.
TRASSIR_CHANNELS_TTL = 300
# Лента жильца — это «что было недавно», а не журнал охраны: ящик на объекте
# хранит неделю и не больше двух тысяч записей, что бы ни творилось на камерах.
TRASSIR_EVENT_RETENTION = 7 * 24 * 3600
TRASSIR_EVENT_CAP = 2000
TRASSIR_STORAGE_KEY = "mega_home_trassir"
# Превью события. Trassir отдаёт полный кадр 1920×1128 (~530 КБ) и уменьшать
# его запросом НЕ УМЕЕТ — ни `width`, ни `size`, ни `quality` он не понимает.
# Значит ужимаем сами, иначе лента из двадцати событий это десять мегабайт.
TRASSIR_THUMB_WIDTH = 480
# ⚠ Кадр превью берётся ПОЗЖЕ метки события на эту секунду. Детектор срабатывает
# на первом изменении картинки — то есть когда причина события ещё только входит
# в кадр, а часто виден лишь её край. Через секунду она в кадре целиком.
# ⚠ УМОЛЧАНИЕ ДЛЯ СТАРЫХ БАНДЛОВ, а не наше решение: сдвиг присылает приложение
# (`?lead=`). Снять вместе с прочими умолчаниями, когда релизный бандл поднимут.
TRASSIR_THUMB_LEAD = 1
TRASSIR_THUMB_TTL = 600
TRASSIR_THUMB_CAP = 50
# Поля кадра с технической информацией камеры/регистратора: время и имя канала
# жгутся по краям картинки. На превью они съедают место и не читаются — только
# отвлекают, поэтому срезаются ДО уменьшения (`trassir._shrink`). Пиксели
# ИСХОДНИКА, не превью: после уменьшения 50px превратились бы в десяток и
# кромсали бы уже сцену.
TRASSIR_CROP_PX = 50
# Клип события: сколько показать ДО метки (движение начинается раньше, чем его
# заметил детектор) и потолок длины, что бы ни стояло в настройке объекта.
TRASSIR_CLIP_LEAD = 10
TRASSIR_CLIP_MAX_SECONDS = 600
# Продление токена видео. Дока обещает 10 секунд жизни без запросов; стенд
# оказался щедрее, но полагаться на чужую щедрость нельзя.
TRASSIR_PING_INTERVAL = 5
# Сколько ждём готовность телефона (`ready`), прежде чем стартовать архив
# вслепую. Только для старых приложений — новые шлют готовность, как только
# тракт собрался. Срок короче прицела проигрывателя (у него 12 с): вслепую
# стартовавший архив ещё должен успеть дойти кадрами.
TRASSIR_READY_TIMEOUT = 6.0
# Сколько открытая, но так и не начатая запись держит токен. Клип живёт от
# «открыть» до переговоров, а между ними жилец успевает передумать: без сторожа
# такой клип пингуется вечно, копя соединения к регистратору (предел на объекте
# может быть не задан вовсе — на стенде `connections_per_ip = -1`). Срок — с
# запасом на дорогу предложения через менеджер.
TRASSIR_CLIP_IDLE_TIMEOUT = 90.0

# ⚠ Пауза между открытием потока и командой архива. ЗАМЕРЕНО НА СТЕНДЕ
# 2026-09-09, и граница у факта узкая — не расширяй её по памяти:
#   * когда регистратору приходится ИСКАТЬ запись (начало окна не попадает в
#     записанный кусок), команда, отданная в ту же миллисекунду, что RTSP PLAY,
#     даёт РОВНО НОЛЬ байтов — навсегда, а не «медленно». Воспроизведено на
#     основном архиве и на суб-, по два прогона;
#   * по НАВЕДЁННОМУ окну нулевая пауза отработала 8 раз из 8.
# Значит это страховка одного случая, а не общая такса. Отсчёт от конца
# переговоров: go2rtc открывает RTSP ДО того, как отдаст SDP-ответ, поэтому
# «переговоры кончились» — заведомо «PLAY уже был», и готовность телефона
# приходит позже паузы сама по себе.
