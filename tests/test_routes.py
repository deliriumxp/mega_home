"""ЗАМОК на список маршрутов интеграции.

⚠ Этот тест не проверяет работу — он не даёт молча завести новый маршрут.
Причина в том, ради чего интеграцию делали тонкой: её код — единственное, что
не обновляется само. Каждый маршрут здесь = релиз HACS и перезапуск Home
Assistant на КАЖДОМ объекте, то есть ручная работа по квартирам.

⚠ Повод завести замок был свой же (2026-09-09): ради выдачи учётки
ретранслятора завели маршрут `/api/ice` и выпустили релиз, хотя подходили два
уже готовых канала. А ревизия следом нашла, что фон плитки дом качал ДВАЖДЫ —
своим старым маршрутом и общим каналом сразу.

**Прежде чем добавлять строку в `ALLOWED`, ответь: почему не подходит ни один
из трёх общих каналов?**

* `HomeConfig` (`home-config.util.ts` в менеджере) — всё, что менеджер ЗНАЕТ и
  что нужно приложению: стили плиток, настройки объекта, список ICE. Едет ОБЕИМ
  дверям приложения (на домене объекта и через менеджер) — цена: поле в
  менеджере плюс строка в приложении;
* `assets` + `/api/asset/{key}` — любой ФАЙЛ менеджера: фоны, звуки, шрифты,
  план этажа. Дом зеркалит по манифесту вслепую — цена: ключ в манифесте;
* `/api/relay` — любой запрос-ответ приложения К МЕНЕДЖЕРУ, дом только несёт.

Если ответ «канал подходит, но так быстрее» — значит маршрут не нужен.
"""

from __future__ import annotations

from mega_home import http as mega_http

# Маршруты, которые действительно обязаны жить в интеграции, и почему.
ALLOWED = {
    # Контракт приложения с домом: состав, состояния, поток изменений, команда,
    # сценарий. Это ДАННЫЕ дома, менеджера в них нет вовсе.
    "/mega-home/api/config",
    "/mega-home/api/states",
    "/mega-home/api/events",
    "/mega-home/api/command",
    "/mega-home/api/scenario",
    # Фотографии, которые делает САМ ЖИЛЕЦ: они принадлежат дому и в менеджер
    # не уезжают вовсе.
    "/mega-home/api/photos",
    "/mega-home/api/photo/{room}",
    # Общий канал файлов менеджера — тот самый, который избавляет от релизов.
    "/mega-home/api/asset/{key:.+}",
    # Общий перенос запроса приложения к менеджеру — по той же причине.
    "/mega-home/api/relay",
    # Видеонаблюдение объекта. Три общих канала тут не подходят, и вот почему:
    # менеджер до регистратора НЕ ДОСТАЁТ (туннеля нет на части парка), значит
    # ни конфигом, ни файлом, ни переносом К МЕНЕДЖЕРУ эти данные не взять — их
    # рождает Trassir в двух метрах от дома и меняет каждые несколько секунд.
    # Ближайший родственник — фотографии жильца: данные, которые живут в доме.
    # ⚠ Просмотр самой записи маршрута НЕ ДОБАВИЛ: клип открывается тем же
    # `webrtc`, что и живая камера (docs/trassir-integration-plan.md, §5а).
    "/mega-home/api/trassir/cameras",
    "/mega-home/api/trassir/events",
    "/mega-home/api/trassir/events/{event}/thumb",
    # ⚠ Открыть запись — маршрут, а закрыть её — НЕТ: закрывается она тем же
    # `webrtc/close`, что и живая камера. Просмотр записи своего сеанса не
    # заводит вовсе (§5а плана), поэтому и двери у него своей нет.
    "/mega-home/api/trassir/events/{event}/play",
    # Живое видео: кадр камеры и сеанс WebRTC со своими сроками. Данные HA,
    # через менеджер они не ходят.
    "/mega-home/api/camera-frame/{tile}",
    "/mega-home/api/webrtc",
    "/mega-home/api/webrtc/close",
    # Раздача самого приложения: его бандл дом скачивает у менеджера и отдаёт
    # с диска, поэтому маршруты нужны здесь.
    "/mega-home/sw.js",
    "/mega-home",
    "/mega-home/{path:.*}",
}


def _routes() -> set[str]:
    return {
        getattr(view, "url")
        for name, view in vars(mega_http).items()
        if name.endswith("View") and isinstance(getattr(view, "url", None), str)
    }


def test_маршруты_интеграции_не_растут_молча() -> None:
    routes = _routes()
    added = routes - ALLOWED
    removed = ALLOWED - routes

    assert not added, (
        f"новый маршрут в интеграции: {sorted(added)}. "
        "Сначала ответь, почему не подходит конфиг, общий канал файлов или "
        "перенос запроса к менеджеру, — см. заголовок этого файла"
    )
    assert not removed, f"маршрут исчез, а список не поправили: {sorted(removed)}"
