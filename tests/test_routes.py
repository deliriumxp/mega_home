"""ЗАМОК на список маршрутов интеграции.

⚠ Этот тест не проверяет работу — он не даёт молча завести новый маршрут.
Причина в том, ради чего интеграцию делали тонкой: её код — единственное, что
не обновляется само. Каждый маршрут здесь = релиз HACS и перезапуск Home
Assistant на КАЖДОМ объекте, то есть ручная работа по квартирам.

⚠ Повод завести замок был свой же (2026-09-09): ради выдачи учётки
ретранслятора завели маршрут `/api/ice` и выпустили релиз, хотя подходили два
уже готовых канала. А ревизия следом нашла, что фон плитки дом качал ДВАЖДЫ —
своим старым маршрутом и общим каналом сразу.

⚠⚠ **Маршрут заводится для КЛАССА УСТРОЙСТВ, а не для производителя** (правило
заказчика, 2026-09-13). Это ВТОРОЕ условие ПОВЕРХ вопроса ниже, а не вместо
него: сначала докажи, что не подходит ни один из трёх общих каналов, и только
потом думай об имени. Удачное имя не делает лишний маршрут нужным.
`api/video/*`, `api/intercom/*` — класс, и второй регистратор приходит в тот же
маршрут. `api/trassir/*`, `api/akuvox/*` — производитель, и каждый следующий
потребует своего маршрута, своей ветки в приложении и переделки базы. Какой
производитель за классом — знает конфиг объекта и модуль дома, а не путь и не
приложение.

⚠ Долг закрыт 2026-09-14: девять путей `api/trassir/*` стали шестью `api/video/*`,
а универсальная дверь — `api/gateway/call`. Три из них (`clips/{clip}/seek`,
`clips/{clip}/command`, `events/{event}/play`) не переименованы, а УДАЛЕНЫ: к
регистратору вела ВТОРАЯ дорога, и две дороги неизбежно расходятся — правку
«`play` после `seek`» сделали в доме, и она не сработала, потому что перемотка
ходит дверью (`docs/plan-video-rework.md`, этап 1). Переходного периода не было
намеренно: объектов три, окно слома открыто одно, и менеджер требует версию
интеграции замком `expected-integration-version.spec.ts`.

**Прежде чем добавлять строку в `ALLOWED`, ответь: почему не подходит ни один
из трёх общих каналов?**

* `HomeConfig` (`home-config.util.ts` в менеджере) — всё, что менеджер ЗНАЕТ и
  что нужно приложению: стили плиток, настройки объекта, список ICE. Едет ОБЕИМ
  дверям приложения (на домене объекта и через менеджер) — цена: поле в
  менеджере плюс строка в приложении;
* `assets` + `/api/asset/{key}` — любой ФАЙЛ менеджера: фоны, звуки, шрифты,
  план этажа. Дом зеркалит по манифесту вслепую — цена: ключ в манифесте;
* `/api/relay` — любой запрос-ответ приложения К МЕНЕДЖЕРУ, дом только несёт.

Если ответ «канал подходит, но так быстрее» — значит маршрут не нужен.
"""

from __future__ import annotations

from mega_home import http as mega_http

# Маршруты, которые действительно обязаны жить в интеграции, и почему.
#
# ⚠ Тонкий шлюз (`docs/plan-thin-gateway.md`): дом — транспорт, процессы и
# хранилище. Видео объекта, WebRTC-переговоры и универсальная дверь по имени
# ушли отсюда вместе с вендорским кодом — их несёт `api/connect`, один
# контракт на TCP/UDP/HTTP/WS (список операций и маршрутов заперт отдельно,
# `tests/test_thin_gateway.py`, замок 2).
ALLOWED = {
    # Контракт приложения с домом: состав, состояния, поток изменений, команда,
    # сценарий, транспорт наружу. Это ДАННЫЕ дома, менеджера в них нет вовсе.
    "/mega-home/api/config",
    "/mega-home/api/states",
    "/mega-home/api/events",
    "/mega-home/api/command",
    "/mega-home/api/scenario",
    "/mega-home/api/connect",
    # Фотографии и кадры, которые делает САМ ЖИЛЕЦ: принадлежат дому, в
    # менеджер не уезжают, обязаны работать без него.
    "/mega-home/api/photos",
    "/mega-home/api/photo/{room}",
    "/mega-home/api/crops",
    "/mega-home/api/crop/{tile}",
    # Общий канал файлов менеджера — тот самый, который избавляет от релизов.
    "/mega-home/api/asset/{key:.+}",
    # Кадр камеры ИСТОЧНИКА (сущность camera.* Home Assistant) плитки: снаружи
    # у приложения нет ни одного адреса Home Assistant (state.picture — это
    # /api/camera_proxy/... самого HA, недостижим), поэтому кадр едет тем же
    # переносом — часть B (источник состояний), не вендор.
    "/mega-home/api/camera-frame/{tile}",
    # Общий перенос запроса приложения к менеджеру — по той же причине.
    "/mega-home/api/relay",
    # Раздача самого приложения: его бандл дом скачивает у менеджера и отдаёт
    # с диска, поэтому маршруты нужны здесь.
    "/mega-home/sw.js",
    "/mega-home",
    "/mega-home/{path:.*}",
}


def _routes() -> set[str]:
    """Маршруты, которые дом ДЕЙСТВИТЕЛЬНО поднимает (`http.VIEWS`)."""
    return {getattr(view, "url") for view in mega_http.VIEWS}


def _declared() -> dict[str, str]:
    """Все классы дверей в модуле — объявленные, независимо от регистрации."""
    return {
        name: getattr(view, "url")
        for name, view in vars(mega_http).items()
        if name.endswith("View") and isinstance(getattr(view, "url", None), str)
    }


def test_объявленная_дверь_обязана_быть_ЗАРЕГИСТРИРОВАНА() -> None:
    """⚠ Замок на МЁРТВЫЙ маршрут, и он куплен дорого.

    `MegaHomeTrassirPreviewView` был объявлен в 0.2.53 и НЕ попал в список
    регистрации — пролежал мёртвым до 0.2.59. Класс есть, тесты зелёные,
    прежний замок (он смотрел на объявленные классы) доволен, а жилец получает
    обычный 404: превью при перемотке «не работает» на всех объектах разом, и
    отличить это от «дом старой версии» снаружи нельзя ничем — ответ
    побайтово совпадает с ответом на выдуманный путь. Полтора суток разбора.

    Поэтому: объявил дверь — зарегистрируй, либо удали класс.
    """
    registered = _routes()
    dead = {
        name: url for name, url in _declared().items() if url not in registered
    }

    assert not dead, (
        f"дверь объявлена, но не поднимается: {sorted(dead)}. "
        "Впиши класс в `http.VIEWS` или удали его — мёртвый маршрут отвечает "
        "жильцу обычным 404, неотличимым от несуществующего пути"
    )


def test_маршруты_интеграции_не_растут_молча() -> None:
    routes = _routes()
    added = routes - ALLOWED
    removed = ALLOWED - routes

    assert not added, (
        f"новый маршрут в интеграции: {sorted(added)}. "
        "Сначала ответь, почему не подходит конфиг, общий канал файлов или "
        "перенос запроса к менеджеру, — см. заголовок этого файла"
    )
    assert not removed, f"маршрут исчез, а список не поправили: {sorted(removed)}"
