def _routes() -> set[str]:
    """Маршруты, которые дом ДЕЙСТВИТЕЛЬНО поднимает (`http.VIEWS`)."""
    return {getattr(view, "url") for view in mega_http.VIEWS}


def _declared() -> dict[str, str]:
    """Все классы дверей в модуле — объявленные, независимо от регистрации."""
    return {
        name: getattr(view, "url")
        for name, view in vars(mega_http).items()
        if name.endswith("View") and isinstance(getattr(view, "url", None), str)
    }


def test_объявленная_дверь_обязана_быть_ЗАРЕГИСТРИРОВАНА() -> None:
    """⚠ Замок на МЁРТВЫЙ маршрут, и он куплен дорого.

    `MegaHomeTrassirPreviewView` был объявлен в 0.2.53 и НЕ попал в список
    регистрации — пролежал мёртвым до 0.2.59. Класс есть, тесты зелёные,
    прежний замок (он смотрел на объявленные классы) доволен, а жилец получает
    обычный 404: превью при перемотке «не работает» на всех объектах разом, и
    отличить это от «дом старой версии» снаружи нельзя ничем — ответ
    побайтово совпадает с ответом на выдуманный путь. Полтора суток разбора.

    Поэтому: объявил дверь — зарегистрируй, либо удали класс.
    """
    registered = _routes()
    dead = {
        name: url for name, url in _declared().items() if url not in registered
    }

    assert not dead, (
        f"дверь объявлена, но не поднимается: {sorted(dead)}. "
        "Впиши класс в `http.VIEWS` или удали его — мёртвый маршрут отвечает "
        "жильцу обычным 404, неотличимым от несуществующего пути"
    )


def test_маршруты_интеграции_не_растут_молча() -> None:
    routes = _routes()
    added = routes - ALLOWED
    removed = ALLOWED - routes

    assert not added, (
        f"новый маршрут в интеграции: {sorted(added)}. "
        "Сначала ответь, почему не подходит конфиг, общий канал файлов или "
        "перенос запроса к менеджеру, — см. заголовок этого файла"
    )
    assert not removed, f"маршрут исчез, а список не поправили: {sorted(removed)}"
